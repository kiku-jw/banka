function depthForIndex(index: number): CoupleDepth {
  if (index < 5) {
    return "warm";
  }
  if (index < 10) {
    return "closer";
  }
  return "deep";
}

function buildCoupleQuestions(): CoupleQuestion[] {
  const questions: CoupleQuestion[] = [];
  for (const group of groups) {
    group.prompts.forEach((text, index) => {
      questions.push({
        id: `couple-${group.theme}-${index + 1}`,
        theme: group.theme,
        depth: depthForIndex(index),
        text,
      });
    });
  }
  return questions;
}

export const coupleQuestions = buildCoupleQuestions();
